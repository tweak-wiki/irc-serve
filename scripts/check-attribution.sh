#!/bin/sh
# Single-author project: every commit is Finn Robinson's.
#
# WHY THIS EXISTS. This is a single-author repository: the operator is the only
# person who has ever worked on it. A commit carrying someone else's name --
# human or assistant -- misattributes the work, whether it arrives as a trailer,
# a footer, or an author field. Rewriting history to strip such lines is the
# wrong tool: it is expensive, it invalidates every SHA, and it only says
# anything about the past.
#
# So the rule is enforced forward instead: this runs in CI over the commit range
# being pushed, and refuses the push. What is checked:
#
#   1. no `Co-Authored-By` / `Signed-off-by` / `Reviewed-by` / `Acked-by`
#      trailer naming anyone but the owner
#   2. no "Generated with ..." / "Generated by ..." footer
#   3. no identity other than the owner's in the AUTHOR or COMMITTER fields
#
# The range is every commit reachable from HEAD but not from the merge base with
# the base branch, so an ordinary PR is checked for what it ADDS. On the default
# branch it falls back to the last 200 commits, which is a bounded sweep rather
# than the whole history on every push.
set -eu

REPO_ROOT=$(cd "$(dirname "$0")/.." && pwd)
cd "$REPO_ROOT"

BASE="${1:-}"
REF="${2:-HEAD}"
# The owner, spelled the way git writes it. Trailer values carry addresses
# ("Name <mail>") while author fields split into name and mail, so both forms
# are matched. Foundation-model addresses are unmistakable (noreply@anthropic,
# openai, etc.) but the rule does not enumerate vendors: anything that is not
# the owner fails, whoever or whatever wrote it.
OWNER_NAME='Finn Robinson|euphonium.ashe.fin'
OWNER_MAIL='TheFirstIstari|euphonium.ashe.f'

if [ -z "$BASE" ]; then
    # No base given: sweep a bounded window of recent history.
    # `git rev-list --max-count` walks back from HEAD without spelling an
    # ancestor range (`HEAD~N..HEAD`), which does not resolve in every clone.
    RANGE="--max-count=200 HEAD"
else
    MB=$(git merge-base "$BASE" "$REF" 2>/dev/null || echo "")
    if [ -z "$MB" ]; then
        RANGE="$REF"
    else
        RANGE="$MB..$REF"
    fi
fi

COUNT=$(git rev-list $RANGE --count 2>/dev/null || echo 0)
echo "check-attribution: scanning $COUNT commit(s) in $RANGE" >&2

STATUS=0

# 1 and 2: trailers and footers in the message body.
# --format=%B gives the raw message; the message is scanned as one blob so a
# trailer cannot hide by being split across a continuation line.
HITS=$(git log --format='%H' $RANGE 2>/dev/null | while read -r sha; do
    body=$(git log -1 --format='%B' "$sha" 2>/dev/null)
    trailers=$(printf '%s\n' "$body" \
        | grep -iE "^(co-authored-by|signed-off-by|reviewed-by|acked-by)[[:space:]]*:" || true)
    if [ -n "$trailers" ] && ! printf '%s\n' "$trailers" \
        | grep -qiE "$OWNER_NAME|$OWNER_MAIL"; then
        printf '  %s  %s\n' "$(printf '%s' "$sha" | cut -c1-9)" \
            "$(git log -1 --format='%s' "$sha" | cut -c1-60)"
    elif printf '%s\n' "$body" \
        | grep -qiE "generated (with|by) "; then
        printf '  %s  %s\n' "$(printf '%s' "$sha" | cut -c1-9)" \
            "$(git log -1 --format='%s' "$sha" | cut -c1-60)"
    fi
done)

if [ -n "$HITS" ]; then
    echo "check-attribution: FAIL: these commits carry someone else's attribution trailer:" >&2
    printf '%s\n' "$HITS" >&2
    STATUS=1
fi

# 3: author or committer identity.
IDHITS=$(git log --format='%an|%ae|%cn|%ce' $RANGE 2>/dev/null | sort -u | \
    grep -viE "$OWNER_NAME|$OWNER_MAIL" | grep -v '^\s*$' || true)
if [ -n "$IDHITS" ]; then
    echo "check-attribution: FAIL: an identity other than the owner's is in an author or committer field:" >&2
    printf '  %s\n' "$IDHITS" >&2
    STATUS=1
fi

if [ "$STATUS" -eq 0 ]; then
    echo "check-attribution: OK: single-author attribution holds in $RANGE" >&2
fi
exit "$STATUS"
